package com.unchunks.echomark.data.ai

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/** 動画の本文を AI に渡す前に整える(チャンネルの行・説明文の宣伝・字幕のノイズを除く)。 */
class VideoAnalysisTextTest {

    private val youtubeBody = listOf(
        "チャンネル: Android開発チャンネル",
        listOf(
            "Jetpack Compose の再コンポーズを減らす方法を解説します。",
            "",
            "0:00 はじめに",
            "1:30 remember の使い方",
            "5:10 derivedStateOf",
            "",
            "▼チャンネル登録はこちら",
            "https://www.youtube.com/@example",
            "#Android #JetpackCompose",
            "━━━━━━━━━━",
            "お仕事のご依頼は example@example.com まで"
        ).joinToString("\n"),
        "字幕(自動生成):\n[音楽]\nえーと 今日は remember の\nremember の使い方を説明します\nそうですね そうですね 大事です",
        "キーワード: Android, Compose"
    ).joinToString("\n\n")

    @Test
    fun チャンネルの行を除く() {
        val prepared = VideoAnalysisText.prepare(youtubeBody)

        assertFalse(prepared, prepared.contains("チャンネル:"))
        assertFalse(prepared, prepared.contains("Android開発チャンネル"))
    }

    @Test
    fun 説明文の宣伝とリンクと飾りを除き_章立てを1行にまとめる() {
        val prepared = VideoAnalysisText.prepare(youtubeBody)

        assertTrue(prepared, prepared.startsWith("チャプター: はじめに / remember の使い方 / derivedStateOf\n\nJetpack Compose の再コンポーズを減らす方法を解説します。"))
        listOf("チャンネル登録", "https://", "#Android", "━━", "ご依頼").forEach {
            assertFalse("$it が残っている: $prepared", prepared.contains(it))
        }
    }

    @Test
    fun 自動生成の字幕から効果音とつなぎ言葉と重なりと繰り返しを除いてつなぐ() {
        val prepared = VideoAnalysisText.prepare(youtubeBody)

        assertTrue(
            prepared,
            prepared.contains("字幕(自動生成):\n今日は remember の 使い方を説明します そうですね 大事です\n\nキーワード: Android, Compose")
        )
    }

    @Test
    fun 手動の字幕は行のまま残す() {
        val transcript = VideoAnalysisText.cleanTranscript("[拍手] 今日は晴れです。\nあのー 明日は雨です。", isAutoGenerated = false)

        assertEquals("今日は晴れです。\n明日は雨です。", transcript)
    }

    @Test
    fun 語の一部のあのは残す() {
        assertEquals("あの人が来た", VideoAnalysisText.cleanTranscript("あの人が来た", isAutoGenerated = true))
    }

    @Test
    fun 長い自動生成の字幕は段落に分けて改行を入れる() {
        val lines = (1..100).joinToString("\n") { "これは${it}番目の字幕の行です" }

        val transcript = VideoAnalysisText.cleanTranscript(lines, isAutoGenerated = true)

        assertTrue(transcript.contains('\n'))
        assertTrue(transcript.lines().all { it.length < 500 })
    }

    @Test
    fun 字幕が無いときは説明文だけを整える() {
        val prepared = VideoAnalysisText.prepare("チャンネル: 料理ch\n\n簡単なカレーの作り方。\nhttps://example.com/recipe\n\nキーワード: カレー")

        assertEquals("簡単なカレーの作り方。\n\nキーワード: カレー", prepared)
    }

    @Test
    fun 章立てが1行だけなら説明文の行として残す() {
        assertEquals("10:00 から配信します", VideoAnalysisText.cleanDescription("10:00 から配信します"))
    }

    @Test
    fun YouTubeの本文の形でなければそのまま渡す() {
        // 動画ファイルの文字起こし。話の中に SNS の名前が出てきても削らない
        val text = "--- 文字起こし ---\nTwitter で話題になった件について話します"

        assertEquals(text, VideoAnalysisText.prepare(text))
    }
}
