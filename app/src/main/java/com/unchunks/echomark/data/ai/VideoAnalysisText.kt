package com.unchunks.echomark.data.ai

/**
 * 動画のブックマークの本文を、要約・タグ付けの AI に渡す前に整える(純粋関数)。
 *
 * YouTube の本文(HtmlContentExtractor.youtubeText)は「チャンネル: 名前」・説明文・「字幕:」以下の字幕・「キーワード:」から成る。
 * 端末内の AI は1回に読める長さが小さく(長い本文は一部を間引いて要約する)、ノイズの分だけ話の中身が入らなくなるため、
 * 次のものを除いて、同じ長さに入る話の量を増やす。保存してある本文は変えない(AI に渡す直前だけ整える)。
 * - チャンネル名の行(要約やタグにチャンネル名が写されるのを防ぐ。要約の後処理には [SummaryCleaner.channelOf] で別に渡す)
 * - 説明文のリンク・ハッシュタグ・SNS や宣伝の行・飾りの線。時刻つきの章立ての行は「チャプター:」の1行にまとめる
 * - 字幕の効果音([音楽] など)・つなぎ言葉(えーと・あのー など)・自動生成の字幕で前の行と重なる部分・続けて繰り返した語
 *
 * 「字幕:」の見出しが無い本文(動画ファイルの文字起こしなど)は、チャンネルの行と説明文の扱いだけを行う。
 */
object VideoAnalysisText {

    fun prepare(text: String): String {
        val withoutChannel = CHANNEL_LINE.replace(text, "")
        val header = TRANSCRIPT_HEADER.find(withoutChannel)
        // YouTube の本文の形でなければ(動画ファイルの文字起こしなど)、話の中身を説明文と取り違えて削らないようそのまま渡す
        if (header == null && withoutChannel.length == text.length) return text
        if (header == null) {
            val (body, keywords) = splitKeywords(withoutChannel)
            return join(cleanDescription(body), keywords)
        }
        val description = withoutChannel.substring(0, header.range.first)
        val (transcript, keywords) = splitKeywords(withoutChannel.substring(header.range.last + 1))
        val isAutoGenerated = header.groupValues[1].isNotEmpty()
        val cleanedTranscript = cleanTranscript(transcript, isAutoGenerated)
        return join(
            cleanDescription(description),
            cleanedTranscript.takeIf { it.isNotBlank() }?.let { header.value.trimEnd() + "\n" + it },
            keywords
        )
    }

    /** 末尾の「キーワード: …」の段落を分ける。 */
    private fun splitKeywords(text: String): Pair<String, String?> {
        val match = KEYWORDS_PARAGRAPH.find(text) ?: return text to null
        return text.substring(0, match.range.first) to match.value.trim()
    }

    private fun join(vararg parts: String?): String =
        parts.mapNotNull { it?.trim()?.takeIf { part -> part.isNotEmpty() } }.joinToString("\n\n")

    /**
     * 説明文から宣伝・リンク・飾りの行を除き、時刻つきの章立ての行(2行以上あるとき)を「チャプター: A / B / …」にまとめて先頭に置く。
     * 行の中身は変えない(残すか除くかだけを決める)。
     */
    internal fun cleanDescription(description: String): String {
        val lines = description.lines().map { it.trim() }
        val chapters = lines.mapNotNull { line -> CHAPTER_LINE.matchEntire(line)?.groupValues?.get(1)?.trim() }
            .filter { it.isNotEmpty() }
        val useChapters = chapters.size >= MIN_CHAPTERS
        val kept = lines.filterNot { line ->
            (useChapters && CHAPTER_LINE.matches(line)) || isNoiseLine(line)
        }
        val body = kept.joinToString("\n").replace(BLANK_LINES, "\n\n").trim()
        val chapterLine = if (useChapters) "チャプター: " + chapters.take(MAX_CHAPTERS).joinToString(" / ") else null
        return join(chapterLine, body)
    }

    /** 説明文の、要約に要らない行か。空行は段落の区切りとして残す。 */
    private fun isNoiseLine(line: String): Boolean {
        if (line.isEmpty()) return false
        if (URL.containsMatchIn(line)) return true
        if (HASHTAGS_ONLY.matches(line)) return true
        if (DECORATION_ONLY.matches(line)) return true
        return PROMOTION_WORDS.any { line.contains(it, ignoreCase = true) }
    }

    /**
     * 字幕を整える。行ごとに効果音とつなぎ言葉を除き、前の行と重なる書き出しを削る。
     * 自動生成の字幕は1行が短い断片なので、空白でつないで段落(約 [PARAGRAPH_CHARS] 文字ごとに改行)にする
     * (改行が多いと分割の目安がずれ、トークンも増える)。手動の字幕は1行1文のことが多いため、行のまま残す。
     */
    internal fun cleanTranscript(transcript: String, isAutoGenerated: Boolean): String {
        val lines = mutableListOf<String>()
        for (raw in transcript.lines()) {
            var line = SOUND_TAG.replace(raw, " ")
            line = FILLER.replace(line, " ")
            line = REPEATED_WORD.replace(line, "$1")
            line = line.replace(WHITESPACE, " ").trim()
            lines.lastOrNull()?.let { previous -> line = removeOverlap(previous, line) }
            if (line.isEmpty() || line == lines.lastOrNull()) continue
            lines += line
        }
        if (!isAutoGenerated) return lines.joinToString("\n")
        val paragraphs = StringBuilder()
        var paragraphLength = 0
        for (line in lines) {
            if (paragraphLength > 0) {
                if (paragraphLength >= PARAGRAPH_CHARS) {
                    paragraphs.append('\n')
                    paragraphLength = 0
                } else {
                    paragraphs.append(' ')
                }
            }
            paragraphs.append(line)
            paragraphLength += line.length
        }
        return paragraphs.toString()
    }

    /**
     * 自動生成の字幕で、前の行の終わりと同じ言葉で次の行が始まる(字幕が流れながら重なる)とき、その重なりを除く。
     * [MIN_OVERLAP_CHARS] 文字より短い重なりは偶然の一致とみなして残す。
     */
    private fun removeOverlap(previous: String, line: String): String {
        val max = minOf(previous.length, line.length)
        for (length in max downTo MIN_OVERLAP_CHARS) {
            if (previous.endsWith(line.substring(0, length))) return line.substring(length).trim()
        }
        return line
    }

    private const val MIN_CHAPTERS = 2
    private const val MAX_CHAPTERS = 30
    private const val MIN_OVERLAP_CHARS = 4
    private const val PARAGRAPH_CHARS = 400

    private val CHANNEL_LINE = Regex("""(?m)^チャンネル: .*(\r?\n)?""")

    /** 「字幕:」「字幕(自動生成):」の見出しの行(HtmlContentExtractor.youtubeText と同じ書き方) */
    private val TRANSCRIPT_HEADER = Regex("""(?m)^字幕(\(自動生成\))?:\r?\n""")

    /** 本文の末尾の「キーワード: …」の段落 */
    private val KEYWORDS_PARAGRAPH = Regex("""(?:^|\n\n)キーワード: [^\n]*\s*$""")

    /** 「0:00 はじめに」「12:34 - まとめ」「1:02:03 質疑応答」のような章立ての行。グループ1が章の名前 */
    private val CHAPTER_LINE = Regex("""^[(（\[]?(?:\d{1,2}:)?\d{1,2}:\d{2}[)）\]]?\s*[-–ー~〜:：|｜]?\s*(.*)$""")

    private val URL = Regex("""https?://|www\.|\.com/|bit\.ly""", RegexOption.IGNORE_CASE)
    private val HASHTAGS_ONLY = Regex("""^(?:[#＃]\S+\s*)+$""")

    /** 記号だけの飾りの行(━━━・＝＝＝・----・▼▼ など) */
    private val DECORATION_ONLY = Regex("""^[\p{Punct}\p{S}ー━─＝=＿_・*＊◆◇■□●○▼▽▲△★☆♪〜~\s]+$""")

    /** 宣伝・SNS・依頼の案内によく出る語。含む行は除く */
    private val PROMOTION_WORDS = listOf(
        "チャンネル登録", "高評価", "グッドボタン", "通知をオン", "ベルマーク", "メンバーシップ", "メンバー登録",
        "Twitter", "Instagram", "TikTok", "Facebook", "Threads", "LINE公式", "Discord", "note.com",
        "お問い合わせ", "お仕事のご依頼", "仕事のご依頼", "案件のご依頼", "ご依頼は", "メールアドレス",
        "スポンサー", "提供:", "提供：", "#PR", "【PR】", "アフィリエイト", "Amazonアソシエイト", "楽天アフィリエイト",
        "使用機材", "撮影機材", "BGM", "効果音", "使用素材", "楽曲提供", "Music:", "Subscribe", "Follow me"
    )

    private val BLANK_LINES = Regex("""\n{3,}""")
    private val WHITESPACE = Regex("""\s+""")

    /** 行の途中の「[音楽]」「[拍手]」「[笑い]」「[Music]」など、角括弧の短い効果音 */
    private val SOUND_TAG = Regex("""[\[［][^\]］\n]{1,12}[\]］]""")

    /**
     * 独立したつなぎ言葉(前後が空白・句読点・行の端のもの)。「あの人」の「あの」のように語の一部のものは残す
     */
    private val FILLER = Regex("""(?<=^|[\s、。])(?:え[ーっ]+と?|えっと|ええと|あの[ー〜]+|あ[ー〜]+|う[ー〜]+ん|ん[ー〜]+|ま[ー〜]+|um+|uh+)(?=[\s、。]|$)""", RegexOption.IGNORE_CASE)

    /** 空白で区切って続けて繰り返した語(「そうですね そうですね」)。2〜20 文字の語だけ */
    private val REPEATED_WORD = Regex("""(?<!\S)(\S{2,20})(?:\s+\1)+(?!\S)""")
}
